/* =================================
   DRAWER SAFE AREA
================================= */

function isPointerNearDrawer(
  event
) {

  const rect =
    drawer
      .getBoundingClientRect();


  const margin =
    SETTINGS.drawerSafeMargin;


  return (
    event.clientX >=
      rect.left - margin &&

    event.clientX <=
      rect.right + margin &&

    event.clientY >=
      rect.top - margin &&

    event.clientY <=
      rect.bottom + margin
  );

}


function startDrawerSafeTracking() {

  if (
    !isDesktopHover() ||
    drawerSafeTracking
  ) {
    return;
  }


  drawerSafeTracking =
    true;


  document.addEventListener(
    "mousemove",
    handleDrawerSafeMove
  );

}


function stopDrawerSafeTracking() {

  if (
    !drawerSafeTracking
  ) {
    return;
  }


  drawerSafeTracking =
    false;


  document.removeEventListener(
    "mousemove",
    handleDrawerSafeMove
  );

}


function handleDrawerSafeMove(
  event
) {

  if (
    isPointerNearDrawer(event)
  ) {
    return;
  }


  stopDrawerSafeTracking();

  closeDrawer();

}


