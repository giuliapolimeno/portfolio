/* =================================
   BUILD CAROUSEL
================================= */

function buildCarousel() {

  carousel.replaceChildren();

  carousel.style.scrollBehavior =
    "auto";

  mediaElements = [];


  projects.forEach(
    (project, projectIndex) => {

      project.media.forEach(
        (media, mediaIndex) => {

          const item =
            document.createElement("div");

          item.className =
            "media-item";

          item.dataset.projectIndex =
            projectIndex;

          item.dataset.mediaIndex =
            mediaIndex;


          /* PLACEHOLDER */

          if (
            media.type === "placeholder"
          ) {

            const placeholder =
              document.createElement("div");

            placeholder.className =
              "media-placeholder";

            placeholder.textContent =
              media.id;

            item.appendChild(
              placeholder
            );

          }


          /* IMAGE / GIF */

          else if (
            media.type === "image"
          ) {

            const image =
              document.createElement("img");

            image.src =
              media.src;

            image.alt =
              media.id ||
              project.title;

            image.loading =
              "eager";

            image.decoding =
              "async";

            image.addEventListener(
              "load",
              handleMediaLayoutChange
            );

            item.appendChild(
              image
            );

          }


          /* VIDEO */

          else if (
            media.type === "video"
          ) {

            const video =
              document.createElement("video");

            video.src =
              media.src;

            video.autoplay =
              true;

            video.loop =
              true;

            video.muted =
              true;

            video.playsInline =
              true;

            video.preload =
              "metadata";

            video.controls =
              false;


            video.addEventListener(
              "loadedmetadata",
              handleMediaLayoutChange
            );


            video.addEventListener(
              "canplay",
              () => {

                if (
                  !state.drawerOpen
                ) {

                  video
                    .play()
                    .catch(() => {});

                }

              }
            );


            item.appendChild(
              video
            );


            if (
              media.externalUrl
            ) {

              const link =
                document.createElement("a");

              link.className =
                "media-external-link";

              link.href =
                media.externalUrl;

              link.target =
                "_blank";

              link.rel =
                "noopener noreferrer";

              link.textContent =
                media.externalLabel ||
                "Watch with sound";

              item.appendChild(
                link
              );

            }

          }


          carousel.appendChild(
            item
          );


          mediaElements.push({
            element: item,
            projectIndex,
            mediaIndex
          });

        }
      );

    }
  );

}


