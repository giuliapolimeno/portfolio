/* =================================
   PROJECT META
================================= */

function buildProjectMeta(project) {

  const fields = [
    {
      key: "team",
      label: "team"
    },
    {
      key: "client",
      label: "client"
    },
    {
      key: "exhibition",
      label: "exhibition"
    }
  ];


  const availableFields =
    fields.filter(
      field =>
        project[field.key]
    );


  if (
    availableFields.length === 0
  ) {
    return "";
  }


  const rows =
    availableFields
      .map(
        field => {

          const value =
            project[field.key];


          if (
            field.key === "exhibition" &&
            typeof value === "object"
          ) {

            if (
              !value.url ||
              value.url === "#"
            ) {

              return `
                <p>
                  ${field.label}: ${value.text}
                </p>
              `;

            }


            return `
              <p>
                ${field.label}:
                <a
                  href="${value.url}"
                  target="_blank"
                  rel="noopener noreferrer"
                  class="project-meta-link"
                >
                  ${value.text}
                </a>
              </p>
            `;

          }


          return `
            <p>
              ${field.label}: ${value}
            </p>
          `;

        }
      )
      .join("");


  return `

    <div class="project-meta">
      ${rows}
    </div>

  `;

}


