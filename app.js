function goToMedia(
  projectIndex,
  mediaIndex
) {

  const target =
    getMediaElement(
      projectIndex,
      mediaIndex
    );


  if (!target) {
    return;
  }


  cancelNavigation();


  const projectChanged =
    projectIndex !==
    state.activeProjectIndex;


  state.activeProjectIndex =
    projectIndex;

  state.activeMediaIndex =
    mediaIndex;


  if (projectChanged) {

    refreshProjectInterface();

  }

  else {

    updateActiveThumbnail();

  }


  animateCarouselTo(
    target.element.offsetTop
  );

}


/* =================================
   ANIMATE CAROUSEL
================================= */

function animateCarouselTo(
  targetScrollTop
) {

  const startScrollTop =
    carousel.scrollTop;


  const distance =
    targetScrollTop -
    startScrollTop;


  if (
    Math.abs(distance) < 1
  ) {

    carousel.scrollTop =
      targetScrollTop;

    updateActiveThumbnail();

    return;
  }


  state.isNavigating =
    true;


  const startTime =
    performance.now();


  function step(now) {

    const progress =
      Math.min(
        (now - startTime) /
        SETTINGS.navigationDuration,
        1
      );


    carousel.scrollTop =
      startScrollTop +
      distance * progress;


    if (
      progress < 1
    ) {

      navigationFrame =
        requestAnimationFrame(
          step
        );

      return;
    }


    carousel.scrollTop =
      targetScrollTop;


    navigationFrame =
      null;

    state.isNavigating =
      false;

    updateActiveThumbnail();

  }


  navigationFrame =
    requestAnimationFrame(
      step
    );

}


/* =================================
   CANCEL NAVIGATION
================================= */

function cancelNavigation() {

  if (
    navigationFrame !== null
  ) {

    cancelAnimationFrame(
      navigationFrame
    );

    navigationFrame =
      null;

  }


  state.isNavigating =
    false;

}


/* =================================
   ACTIVE MEDIA
================================= */

function detectActiveMedia() {

  if (
    state.isNavigating ||
    mediaElements.length === 0
  ) {
    return;
  }


  const carouselTop =
    carousel
      .getBoundingClientRect()
      .top;


  let activeItem =
    mediaElements[0];


  for (
    const item of mediaElements
  ) {

    const top =
      item.element
        .getBoundingClientRect()
        .top;


    if (
      top <= carouselTop + 1
    ) {

      activeItem =
        item;

    }

    else {

      break;

    }

  }


  const projectChanged =
    activeItem.projectIndex !==
    state.activeProjectIndex;


  const mediaChanged =
    activeItem.mediaIndex !==
    state.activeMediaIndex;


  if (
    !projectChanged &&
    !mediaChanged
  ) {
    return;
  }


  state.activeProjectIndex =
    activeItem.projectIndex;

  state.activeMediaIndex =
    activeItem.mediaIndex;


  if (projectChanged) {

    refreshProjectInterface();

    return;

  }


  if (mediaChanged) {

    updateActiveThumbnail();

  }

}


